export function formatContent(text: string): string {
    if (!text) return '';
    return text.replace(/\{\{([^}]+)\}\}/g, (match, p1) => {
        const key = p1.trim();
        const label = FIELD_VARIABLE_MAPPINGS[key] || key;
        return `<span class="bg-brand-50 text-brand-600 px-1.5 py-0.5 rounded-md text-[0.85em] font-bold border border-brand-200/60 shadow-xs whitespace-nowrap inline-block align-baseline mx-0.5 select-none" contenteditable="false">${label}</span>`;
    });
}
