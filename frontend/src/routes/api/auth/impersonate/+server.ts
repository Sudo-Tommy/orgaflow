import { json, error } from '@sveltejs/kit';
import type { RequestHandler } from './$types';
import PocketBase from 'pocketbase';
import crypto from 'crypto';

const PB_URL = process.env.POCKETBASE_URL || 'http://127.0.0.1:8090';
const PB_ADMIN_EMAIL = process.env.PB_ADMIN_EMAIL || 't.jenzsch@ihre-seniorenassistenz.com';
const PB_ADMIN_PASSWORD = process.env.PB_ADMIN_PASSWORD || '6AZePm6YLLa2DGE';
const JWT_SECRET = process.env.JWT_SECRET || '*LzR+D/EZW6$8zi';

function signPortalJwt(payload: Record<string, any>, secret: string): string {
    const header = Buffer.from(JSON.stringify({ alg: 'HS256', typ: 'JWT' })).toString('base64url');
    const body = Buffer.from(JSON.stringify({
        ...payload,
        iat: Math.floor(Date.now() / 1000),
        exp: Math.floor(Date.now() / 1000) + (30 * 86400)
    })).toString('base64url');
    const signature = crypto.createHmac('sha256', secret).update(`${header}.${body}`).digest('base64url');
    return `${header}.${body}.${signature}`;
}

async function getAdminPb(): Promise<PocketBase> {
    const pbAdmin = new PocketBase(PB_URL);
    pbAdmin.autoCancellation(false);
    await pbAdmin.collection('_superusers').authWithPassword(PB_ADMIN_EMAIL, PB_ADMIN_PASSWORD);
    return pbAdmin;
}

export const POST: RequestHandler = async ({ request }) => {
    try {
        const authHeader = request.headers.get('authorization') || '';
        const token = authHeader.replace(/^Bearer\s+/i, '').trim();

        if (!token) {
            throw error(401, 'Authentifizierung erforderlich.');
        }

        const pbAdmin = await getAdminPb();

        // 1. Berechtigung des Anfragenden verifizieren (Muss Inhaber / Superadmin sein)
        const callerPb = new PocketBase(PB_URL);
        callerPb.authStore.save(token, null);
        let callerUser: any = null;
        try {
            callerUser = await callerPb.collection('users').authRefresh();
        } catch {
            try {
                callerUser = await callerPb.collection('_superusers').authRefresh();
            } catch {
                throw error(401, 'Ungültige Sitzung.');
            }
        }

        const callerRecord = callerUser?.record;
        const isSuper = callerPb.authStore.isSuperuser;
        const isOwner = isSuper || 
            callerRecord?.role === 'developer' ||
            callerRecord?.role === 'superadmin' || 
            callerRecord?.role === 'owner' || 
            callerRecord?.email === PB_ADMIN_EMAIL ||
            callerRecord?.email === 'tommy.jenzsch@ihre-seniorenassistenz.com' ||
            callerRecord?.email?.toLowerCase().includes('jenzsch');

        if (!isOwner) {
            throw error(403, 'Ausschließlich der Inhaber darf andere Benutzerkonten imitieren.');
        }

        const body = await request.json().catch(() => ({}));
        const { targetId, targetType = 'user' } = body;

        if (!targetId) {
            throw error(400, 'targetId ist erforderlich.');
        }

        let authToken = '';
        let authRecord: any = null;
        let portalToken = '';
        let targetName = 'Benutzer';
        let targetRole = 'user';

        if (targetType === 'user') {
            // Regulärer Benutzer oder Mitarbeiter aus 'users'
            const user = await pbAdmin.collection('users').getOne(targetId);
            const imp = await pbAdmin.collection('users').impersonate(user.id, 86400);
            authToken = imp.authStore.token;
            authRecord = imp.authStore.record;
            targetName = `${user.name_first || ''} ${user.name_last || ''}`.trim() || user.username || user.email;
            targetRole = user.role || 'user';
        } else {
            // Klient aus 'clients'
            const client = await pbAdmin.collection('clients').getOne(targetId);
            targetName = `${client.name_first || ''} ${client.name_last || ''}`.trim();
            targetRole = 'client';

            // Suche oder erstelle einen verknüpften Gast-Nutzer für PB-Regeln
            let linkedUser: any = null;
            try {
                const existing = await pbAdmin.collection('users').getList(1, 1, {
                    filter: `clients ~ "${client.id}"`
                });
                if (existing.items.length > 0) {
                    linkedUser = existing.items[0];
                }
            } catch {}

            if (!linkedUser) {
                try {
                    const fallbackEmail = client.email || `client_${client.id}@portal.local`;
                    linkedUser = await pbAdmin.collection('users').create({
                        username: `client_${client.id.slice(0, 8)}`,
                        email: fallbackEmail,
                        emailVisibility: false,
                        password: `AutoGenerated_${client.id}_!`,
                        passwordConfirm: `AutoGenerated_${client.id}_!`,
                        name_first: client.name_first || 'Klient',
                        name_last: client.name_last || '',
                        role: 'guest',
                        verified: true,
                        clients: [client.id]
                    });
                } catch (createErr: any) {
                    // Falls E-Mail schon existiert, lade diesen
                    const existingUser = await pbAdmin.collection('users').getFirstListItem(`email = "${client.email}"`).catch(() => null);
                    if (existingUser) linkedUser = existingUser;
                }
            }

            if (linkedUser) {
                const imp = await pbAdmin.collection('users').impersonate(linkedUser.id, 86400);
                authToken = imp.authStore.token;
                authRecord = imp.authStore.record;
            }

            // Portal JWT für Microservice-Routen
            portalToken = signPortalJwt({
                id: client.id,
                type: 'client',
                email: client.email || '',
                name_first: client.name_first || '',
                name_last: client.name_last || '',
                salutation: client.salutation || ''
            }, JWT_SECRET);
        }

        // Audit-Log für Nachvollziehbarkeit & Sicherheit
        try {
            const callerName = `${callerRecord?.name_first || ''} ${callerRecord?.name_last || ''}`.trim() || callerRecord?.email || 'Tommy Jenzsch';
            await pbAdmin.collection('audit_logs').create({
                user_name: callerName,
                user_role: 'owner',
                action: 'OWNER_IMPERSONATION',
                route: '/api/auth/impersonate',
                details: `Inhaber hat sich als ${targetName} (${targetRole}, ID: ${targetId}) angemeldet.`
            });
        } catch (logErr) {
            console.warn('[Impersonate] Audit-Log Warnung:', logErr);
        }

        return json({
            success: true,
            token: authToken,
            record: authRecord,
            portalToken,
            targetName,
            targetRole,
            targetType
        });
    } catch (err: any) {
        console.error('[Impersonate Endpoint Error]:', err);
        return json({ success: false, error: err.message || 'Fehler beim Benutzerwechsel.' }, { status: err.status || 500 });
    }
};
