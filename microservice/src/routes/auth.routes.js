import { Router } from 'express';
import { getAdminPb, createClientPb } from '../services/pb.js';
import { createPortalToken } from '../services/portal/portalAuthService.js';

const router = Router();

const IMPERSONATE_ROUTES = [
    '/api/emails/auth/impersonate',
    '/api/auth/impersonate',
    '/auth/impersonate',
    '/api/emails/portal/impersonate',
    '/portal/impersonate'
];

async function performImpersonate(pbAdmin, userId, duration = 86400) {
    if (typeof pbAdmin.collection('users').impersonate === 'function') {
        const imp = await pbAdmin.collection('users').impersonate(userId, duration);
        return { token: imp.authStore.token, record: imp.authStore.record };
    }
    const res = await pbAdmin.send(`/api/collections/users/impersonate/${encodeURIComponent(userId)}`, {
        method: 'POST',
        body: { duration }
    });
    return { token: res.token, record: res.record };
}

router.post(IMPERSONATE_ROUTES, async (req, res) => {
    try {
        const authHeader = req.headers.authorization || '';
        const token = authHeader.replace(/^Bearer\s+/i, '').trim();

        if (!token) {
            return res.status(401).json({ success: false, error: 'Authentifizierung erforderlich.' });
        }

        const pbAdmin = await getAdminPb();

        // 1. Berechtigung verifizieren (Inhaber / Superadmin)
        const callerPb = createClientPb(token);
        let callerUser = null;
        try {
            callerUser = await callerPb.collection('users').authRefresh();
        } catch {
            try {
                callerUser = await callerPb.collection('_superusers').authRefresh();
            } catch {
                return res.status(401).json({ success: false, error: 'Ungültige Sitzung.' });
            }
        }

        const callerRecord = callerUser?.record;
        const isSuper = callerPb.authStore.isSuperuser;
        const adminEmail = process.env.PB_ADMIN_EMAIL || 't.jenzsch@ihre-seniorenassistenz.com';
        const isOwner = isSuper ||
            callerRecord?.role === 'developer' ||
            callerRecord?.role === 'superadmin' ||
            callerRecord?.role === 'owner' ||
            callerRecord?.email === adminEmail ||
            callerRecord?.email === 'tommy.jenzsch@ihre-seniorenassistenz.com' ||
            callerRecord?.email?.toLowerCase().includes('jenzsch');

        if (!isOwner) {
            return res.status(403).json({ success: false, error: 'Ausschließlich der Inhaber darf Benutzerkonten imitieren.' });
        }

        const { targetId, targetType = 'user' } = req.body || {};
        if (!targetId) {
            return res.status(400).json({ success: false, error: 'targetId ist erforderlich.' });
        }

        let authToken = '';
        let authRecord = null;
        let portalToken = '';
        let targetName = 'Benutzer';
        let targetRole = 'user';

        if (targetType === 'user') {
            const user = await pbAdmin.collection('users').getOne(targetId);
            const imp = await performImpersonate(pbAdmin, user.id, 86400);
            authToken = imp.token;
            authRecord = imp.record;
            targetName = `${user.name_first || ''} ${user.name_last || ''}`.trim() || user.username || user.email;
            targetRole = user.role || 'user';
        } else {
            const client = await pbAdmin.collection('clients').getOne(targetId);
            targetName = `${client.name_first || ''} ${client.name_last || ''}`.trim();
            targetRole = 'client';

            let linkedUser = null;
            try {
                const existing = await pbAdmin.collection('users').getList(1, 1, {
                    filter: `clients ~ "${client.id}"`
                });
                if (existing.items.length > 0) {
                    linkedUser = existing.items[0];
                }
            } catch {}

            if (!linkedUser) {
                try {
                    const fallbackEmail = client.email || `client_${client.id}@portal.local`;
                    linkedUser = await pbAdmin.collection('users').create({
                        username: `client_${client.id.slice(0, 8)}`,
                        email: fallbackEmail,
                        emailVisibility: false,
                        password: `AutoGenerated_${client.id}_!`,
                        passwordConfirm: `AutoGenerated_${client.id}_!`,
                        name_first: client.name_first || 'Klient',
                        name_last: client.name_last || '',
                        role: 'guest',
                        verified: true,
                        clients: [client.id]
                    });
                } catch {
                    if (client.email) {
                        linkedUser = await pbAdmin.collection('users').getFirstListItem(`email = "${client.email}"`).catch(() => null);
                    }
                }
            }

            if (linkedUser) {
                const imp = await performImpersonate(pbAdmin, linkedUser.id, 86400);
                authToken = imp.token;
                authRecord = imp.record;
            }

            portalToken = createPortalToken({
                id: client.id,
                email: client.email || '',
                name_first: client.name_first || '',
                name_last: client.name_last || '',
                salutation: client.salutation || ''
            }, 'client', '30d');
        }

        try {
            const callerName = `${callerRecord?.name_first || ''} ${callerRecord?.name_last || ''}`.trim() || callerRecord?.email || 'Tommy Jenzsch';
            await pbAdmin.collection('audit_logs').create({
                user_name: callerName,
                user_role: 'owner',
                action: 'OWNER_IMPERSONATION',
                route: '/api/auth/impersonate',
                details: `Inhaber hat sich als ${targetName} (${targetRole}, ID: ${targetId}) angemeldet.`
            });
        } catch (logErr) {
            console.warn('[Impersonate] Audit-Log Warnung:', logErr.message);
        }

        return res.json({
            success: true,
            token: authToken,
            record: authRecord,
            portalToken,
            targetName,
            targetRole,
            targetType
        });
    } catch (err) {
        console.error('[Impersonate Endpoint Error]:', err);
        return res.status(err.status || 500).json({ success: false, error: err.message || 'Fehler beim Benutzerwechsel.' });
    }
});

export default router;
